import 'dart:io';

/// CLI tool to generate Swift ActivityKit and WidgetKit boilerplate.
///
/// Usage:
///   dart run flutter_activity_kit:generate_swift --name DeliveryActivity
void main(List<String> args) {
  String activityName = 'LiveActivity';
  String targetDir = 'ios/LiveActivityWidget';

  for (int i = 0; i < args.length; i++) {
    if (args[i] == '--name' && i + 1 < args.length) {
      activityName = args[i + 1];
    } else if (args[i] == '--output' && i + 1 < args.length) {
      targetDir = args[i + 1];
    }
  }

  if (!RegExp(r'^[A-Z][A-Za-z0-9]*$').hasMatch(activityName)) {
    stderr.writeln('--name must be a valid PascalCase Swift type prefix.');
    exitCode = 64;
    return;
  }

  final swiftContent = generateSwiftTemplate(activityName);

  final outDir = Directory(targetDir);
  if (!outDir.existsSync()) {
    outDir.createSync(recursive: true);
  }

  final outFile = File('${outDir.path}/${activityName}Widget.swift');
  outFile.writeAsStringSync(swiftContent);

  // ignore: avoid_print
  print('================================================================');
  // ignore: avoid_print
  print('  Successfully generated Swift Live Activity Widget!');
  // ignore: avoid_print
  print('  File: ${outFile.path}');
  // ignore: avoid_print
  print('================================================================');
  // ignore: avoid_print
  print('');
  // ignore: avoid_print
  print('Xcode Setup Steps:');
  // ignore: avoid_print
  print('1. Open your iOS project in Xcode.');
  // ignore: avoid_print
  print('2. Go to File -> New -> Target -> Widget Extension.');
  // ignore: avoid_print
  print('3. Name it "LiveActivityWidget" and check "Include Live Activity".');
  // ignore: avoid_print
  print('4. Add ${outFile.path} to your Widget Extension target.');
  // ignore: avoid_print
  print('5. Add "NSSupportsLiveActivities = YES" to your Runner Info.plist.');
  // ignore: avoid_print
  print('================================================================');
}

String generateSwiftTemplate(String name) {
  return '''//
//  ${name}Widget.swift
//  Generated by flutter_activity_kit
//

import ActivityKit
import WidgetKit
import SwiftUI

// MARK: - Activity Attributes (Static & Dynamic State)
/// Must stay byte-for-byte compatible with plugin's FlutterActivityAttributes.
public struct FlutterActivityAttributes: ActivityAttributes {
    public struct ContentState: Codable, Hashable {
        public var data: [String: String]
        public var progress: Double?
        public var title: String?
        public var message: String?
        public var status: String?
        public var timerStartDate: Date?
        public var timerTargetDate: Date?
        public var timerCountsDown: Bool?
        public var timerIsPaused: Bool?

        public init(
            data: [String: String] = [:],
            progress: Double? = nil,
            title: String? = nil,
            message: String? = nil,
            status: String? = nil,
            timerStartDate: Date? = nil,
            timerTargetDate: Date? = nil,
            timerCountsDown: Bool? = nil,
            timerIsPaused: Bool? = nil
        ) {
            self.data = data
            self.progress = progress
            self.title = title
            self.message = message
            self.status = status
            self.timerStartDate = timerStartDate
            self.timerTargetDate = timerTargetDate
            self.timerCountsDown = timerCountsDown
            self.timerIsPaused = timerIsPaused
        }
    }

    public var activityType: String
    public var staticData: [String: String]

    public init(activityType: String, staticData: [String: String] = [:]) {
        self.activityType = activityType
        self.staticData = staticData
    }
}

// MARK: - Widget Definition
@available(iOS 16.1, *)
public struct ${name}Widget: Widget {
    public var body: some WidgetConfiguration {
        ActivityConfiguration(for: FlutterActivityAttributes.self) { context in
            // MARK: Lock Screen & Home Screen Banner
            LockScreenLiveActivityView(context: context)
                .activityBackgroundTint(Color.black.opacity(0.85))
                .activitySystemActionForegroundColor(Color.white)
        } dynamicIsland: { context in
            // MARK: Dynamic Island
            DynamicIsland {
                // Expanded Leading
                DynamicIslandExpandedRegion(.leading) {
                    HStack(spacing: 6) {
                        Image(systemName: "bolt.fill")
                            .foregroundColor(.cyan)
                        Text(context.state.status ?? "Active")
                            .font(.caption2)
                            .fontWeight(.semibold)
                            .foregroundColor(.white)
                    }
                    .padding(.leading, 8)
                }

                // Expanded Trailing
                DynamicIslandExpandedRegion(.trailing) {
                    Text("\\(Int((context.state.progress ?? 0) * 100))%")
                        .font(.caption)
                        .fontWeight(.bold)
                        .foregroundColor(.green)
                        .padding(.trailing, 8)
                }

                // Expanded Center / Bottom
                DynamicIslandExpandedRegion(.bottom) {
                    VStack(alignment: .leading, spacing: 6) {
                        Text(context.state.title ?? "Live Activity")
                            .font(.headline)
                            .foregroundColor(.white)
                        Text(context.state.message ?? "")
                            .font(.subheadline)
                            .foregroundColor(.gray)

                        // Progress bar
                        ProgressView(value: context.state.progress ?? 0, total: 1.0)
                            .tint(.cyan)
                    }
                    .padding(.horizontal, 10)
                    .padding(.bottom, 8)
                }
            } compactLeading: {
                // Compact Leading Pill
                HStack(spacing: 4) {
                    Image(systemName: "bolt.fill")
                        .foregroundColor(.cyan)
                    Text(context.state.status ?? "Active")
                        .font(.caption2)
                        .fontWeight(.semibold)
                }
            } compactTrailing: {
                // Compact Trailing Pill
                Text("\\(Int((context.state.progress ?? 0) * 100))%")
                    .font(.caption2)
                    .fontWeight(.bold)
                    .foregroundColor(.green)
            } minimal: {
                // Minimal Bubble
                Image(systemName: "bolt.fill")
                    .foregroundColor(.cyan)
            }
        }
    }
}

// MARK: - Lock Screen View
@available(iOS 16.1, *)
struct LockScreenLiveActivityView: View {
    let context: ActivityViewContext<FlutterActivityAttributes>

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            HStack {
                Label(context.state.title ?? "Live Activity", systemImage: "sparkles")
                    .font(.headline)
                    .foregroundColor(.white)
                Spacer()
                Text(context.state.status ?? "Active")
                    .font(.caption)
                    .padding(.horizontal, 8)
                    .padding(.vertical, 4)
                    .background(Capsule().fill(Color.cyan.opacity(0.3)))
                    .foregroundColor(.cyan)
            }

            Text(context.state.message ?? "")
                .font(.subheadline)
                .foregroundColor(.white.opacity(0.85))

            ProgressView(value: context.state.progress ?? 0, total: 1.0)
                .tint(.cyan)

            Link(
                destination: URL(
                    string: "flutteractivitykit://action/open?activityId=\\(context.activityID)"
                )!
            ) {
                Label("Open", systemImage: "arrow.up.right.square")
                    .font(.caption)
            }
        }
        .padding(16)
        .background(Color.black.opacity(0.8))
    }
}
''';
}
